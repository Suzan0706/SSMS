"""Front office (admission inquiries, school calendar), staff attendance and leave (migration 0013)."""

import uuid
from datetime import date, datetime, time

from sqlalchemy import Date, DateTime, SmallInteger, String, Time
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, SoftDeleteMixin, TenantMixin


class AdmissionInquiry(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "admission_inquiries"
    full_name: Mapped[str] = mapped_column(String(120))
    phone: Mapped[str | None] = mapped_column(String(15))
    email: Mapped[str | None] = mapped_column(String(254))
    class_id: Mapped[uuid.UUID | None]
    source: Mapped[str] = mapped_column(String(12), default="WALK_IN")
    message: Mapped[str | None] = mapped_column(String(500))
    follow_up_on: Mapped[date | None] = mapped_column(Date)
    notes: Mapped[str | None] = mapped_column(String(1000))
    status: Mapped[str] = mapped_column(String(10), default="OPEN")
    application_id: Mapped[uuid.UUID | None]


class SchoolEvent(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "school_events"
    title_en: Mapped[str] = mapped_column(String(120))
    title_sw: Mapped[str] = mapped_column(String(120))
    starts_on: Mapped[date] = mapped_column(Date)
    ends_on: Mapped[date] = mapped_column(Date)
    audience: Mapped[str] = mapped_column(String(10), default="ALL")


class StaffAttendance(TenantMixin, Base):
    __tablename__ = "staff_attendance"
    staff_id: Mapped[uuid.UUID]
    on_date: Mapped[date] = mapped_column(Date)
    status: Mapped[str] = mapped_column(String(8))
    source: Mapped[str] = mapped_column(String(6), default="MANUAL")
    time_in: Mapped[time | None] = mapped_column(Time)
    time_out: Mapped[time | None] = mapped_column(Time)
    note: Mapped[str | None] = mapped_column(String(200))


class LeaveType(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "leave_types"
    name_en: Mapped[str] = mapped_column(String(60))
    name_sw: Mapped[str] = mapped_column(String(60))
    applies_to: Mapped[str] = mapped_column(String(7))
    days_per_year: Mapped[int | None] = mapped_column(SmallInteger)


class LeaveRequest(TenantMixin, Base):
    __tablename__ = "leave_requests"  # `period` (daterange) is generated by the database
    leave_type_id: Mapped[uuid.UUID]
    staff_id: Mapped[uuid.UUID | None]
    student_id: Mapped[uuid.UUID | None]
    start_date: Mapped[date] = mapped_column(Date)
    end_date: Mapped[date] = mapped_column(Date)
    reason: Mapped[str] = mapped_column(String(500))
    status: Mapped[str] = mapped_column(String(9), default="PENDING")
    decided_by: Mapped[uuid.UUID | None]
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    decision_note: Mapped[str | None] = mapped_column(String(300))
