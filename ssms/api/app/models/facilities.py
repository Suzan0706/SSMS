"""Facilities: hostels, rooms, accommodation requests and allocations; buses, routes, stops and transport
assignments; venues and events (design/sql/schema.sql §10). Room, bus and venue capacity are enforced by the
database (fn_capacity_guard), venue overlaps by an EXCLUDE constraint."""

import uuid
from datetime import date, datetime, time
from decimal import Decimal

from sqlalchemy import DateTime, Numeric, SmallInteger, String
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, SoftDeleteMixin, TenantMixin
from app.models.enums import AccommodationStatus, BusStatus, HostelGender


class Hostel(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "hostels"
    name: Mapped[str] = mapped_column(String(60))
    gender: Mapped[HostelGender]
    warden_staff_id: Mapped[uuid.UUID | None]


class HostelRoom(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "hostel_rooms"
    hostel_id: Mapped[uuid.UUID]
    name: Mapped[str] = mapped_column(String(20))
    capacity: Mapped[int] = mapped_column(SmallInteger)


class AccommodationRequest(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "accommodation_requests"
    student_id: Mapped[uuid.UUID]
    term_id: Mapped[uuid.UUID]
    preferred_hostel_id: Mapped[uuid.UUID | None]
    status: Mapped[AccommodationStatus] = mapped_column(default=AccommodationStatus.PENDING)
    decided_by: Mapped[uuid.UUID | None]
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    note: Mapped[str | None] = mapped_column(String(300))


class HostelAllocation(TenantMixin, Base):
    __tablename__ = "hostel_allocations"
    student_id: Mapped[uuid.UUID]
    hostel_room_id: Mapped[uuid.UUID]
    term_id: Mapped[uuid.UUID]
    request_id: Mapped[uuid.UUID | None]
    allocated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now().astimezone())
    vacated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Bus(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "buses"
    bus_no: Mapped[str] = mapped_column(String(12))
    capacity: Mapped[int] = mapped_column(SmallInteger)
    driver_staff_id: Mapped[uuid.UUID | None]
    status: Mapped[BusStatus] = mapped_column(default=BusStatus.ACTIVE)


class Route(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "routes"
    name: Mapped[str] = mapped_column(String(60))
    description: Mapped[str | None] = mapped_column(String(300))
    term_fee_tzs: Mapped[Decimal] = mapped_column(Numeric(14, 2), default=Decimal("0"))


class RouteStop(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "route_stops"
    route_id: Mapped[uuid.UUID]
    seq: Mapped[int] = mapped_column(SmallInteger)
    name: Mapped[str] = mapped_column(String(60))
    pickup_time: Mapped[time]


class TransportAssignment(TenantMixin, Base):
    __tablename__ = "transport_assignments"
    student_id: Mapped[uuid.UUID]
    bus_id: Mapped[uuid.UUID]
    stop_id: Mapped[uuid.UUID]
    term_id: Mapped[uuid.UUID]
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Venue(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "venues"
    name: Mapped[str] = mapped_column(String(60))
    total_seats: Mapped[int] = mapped_column(SmallInteger)


class VenueEvent(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "venue_events"  # `slot` (timerange) is generated by the database
    venue_id: Mapped[uuid.UUID]
    name: Mapped[str] = mapped_column(String(100))
    event_date: Mapped[date]
    time_start: Mapped[time]
    time_end: Mapped[time]
    seats_occupied: Mapped[int] = mapped_column(SmallInteger, default=0)
    organiser_id: Mapped[uuid.UUID | None]
