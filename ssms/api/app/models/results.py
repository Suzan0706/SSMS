"""Enrolment workflow, timetable, exams, marks and the frozen results (see design/sql/schema.sql §5–7)."""

import uuid
from datetime import date, datetime, time
from decimal import Decimal

from sqlalchemy import CHAR, DateTime, Integer, Numeric, SmallInteger, String
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, SoftDeleteMixin, TenantMixin
from app.models.enums import AmendmentStatus, ApplicationStatus, DocumentStatus, ExamKind


class EnrolmentRequirement(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "enrolment_requirements"
    education_level_id: Mapped[uuid.UUID | None]
    class_id: Mapped[uuid.UUID | None]
    name_en: Mapped[str] = mapped_column(String(100))
    name_sw: Mapped[str] = mapped_column(String(100))
    description: Mapped[str | None] = mapped_column(String(300))
    is_required: Mapped[bool] = mapped_column(default=True)


class EnrolmentApplication(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "enrolment_applications"
    application_no: Mapped[str] = mapped_column(String(20))
    student_id: Mapped[uuid.UUID]
    class_id: Mapped[uuid.UUID]
    combination_id: Mapped[uuid.UUID | None]
    academic_year_id: Mapped[uuid.UUID]
    status: Mapped[ApplicationStatus] = mapped_column(default=ApplicationStatus.INQUIRED)
    submitted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    decided_by: Mapped[uuid.UUID | None]
    decision_reason: Mapped[str | None] = mapped_column(String(300))


class EnrolmentDocument(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "enrolment_documents"
    application_id: Mapped[uuid.UUID]
    requirement_id: Mapped[uuid.UUID]
    file_key: Mapped[str] = mapped_column(String(255))
    file_name: Mapped[str] = mapped_column(String(255))
    mime_type: Mapped[str] = mapped_column(String(50))
    size_bytes: Mapped[int] = mapped_column(Integer)
    sha256: Mapped[str] = mapped_column(CHAR(64))
    validation_status: Mapped[DocumentStatus] = mapped_column(default=DocumentStatus.PENDING)
    validated_by: Mapped[uuid.UUID | None]
    validated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    comment: Mapped[str | None] = mapped_column(String(300))


class TimetableSlot(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "timetable_slots"  # `slot` (timerange) is generated by the database
    term_id: Mapped[uuid.UUID]
    stream_id: Mapped[uuid.UUID]
    subject_id: Mapped[uuid.UUID]
    staff_id: Mapped[uuid.UUID]
    room_id: Mapped[uuid.UUID]
    day_of_week: Mapped[int] = mapped_column(SmallInteger)
    time_start: Mapped[time]
    time_end: Mapped[time]


class ExamSession(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "exam_sessions"
    term_id: Mapped[uuid.UUID]
    name_en: Mapped[str] = mapped_column(String(60))
    name_sw: Mapped[str] = mapped_column(String(60))
    kind: Mapped[ExamKind]
    start_date: Mapped[date]
    end_date: Mapped[date]


class Exam(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "exams"  # `slot` (timerange) is generated by the database
    exam_session_id: Mapped[uuid.UUID]
    class_id: Mapped[uuid.UUID]
    subject_id: Mapped[uuid.UUID]
    room_id: Mapped[uuid.UUID | None]
    exam_date: Mapped[date]
    time_start: Mapped[time]
    time_end: Mapped[time]


class MarkEntry(TenantMixin, SoftDeleteMixin, Base):
    __tablename__ = "mark_entries"
    enrolment_id: Mapped[uuid.UUID]
    subject_id: Mapped[uuid.UUID]
    component_id: Mapped[uuid.UUID]
    score: Mapped[Decimal | None] = mapped_column(Numeric(6, 2))
    is_absent: Mapped[bool] = mapped_column(default=False)
    entered_by: Mapped[uuid.UUID]
    version: Mapped[int] = mapped_column(Integer, default=1)
    client_updated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    locked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class ResultPublication(TenantMixin, Base):
    __tablename__ = "result_publications"
    term_id: Mapped[uuid.UUID]
    class_id: Mapped[uuid.UUID]
    grading_scheme_id: Mapped[uuid.UUID]
    scheme_version: Mapped[int] = mapped_column(SmallInteger)
    published_by: Mapped[uuid.UUID]
    published_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


class ResultAmendment(TenantMixin, Base):
    __tablename__ = "result_amendments"
    published_result_id: Mapped[uuid.UUID]
    new_score: Mapped[Decimal] = mapped_column(Numeric(5, 2))
    reason: Mapped[str] = mapped_column(String(300))
    requested_by: Mapped[uuid.UUID]
    status: Mapped[AmendmentStatus] = mapped_column(default=AmendmentStatus.PENDING)
    decided_by: Mapped[uuid.UUID | None]
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    decision_note: Mapped[str | None] = mapped_column(String(300))


class PublishedResult(TenantMixin, Base):
    __tablename__ = "published_results"  # frozen: written only by publish_results / amend_result
    publication_id: Mapped[uuid.UUID]
    enrolment_id: Mapped[uuid.UUID]
    subject_id: Mapped[uuid.UUID]
    final_score: Mapped[Decimal] = mapped_column(Numeric(5, 2))
    letter_grade: Mapped[str] = mapped_column(String(2))
    points: Mapped[int] = mapped_column(SmallInteger)
    subject_position: Mapped[int] = mapped_column(SmallInteger)
    supersedes_id: Mapped[uuid.UUID | None]
    amendment_id: Mapped[uuid.UUID | None]


class StudentTermSummary(TenantMixin, Base):
    __tablename__ = "student_term_summaries"  # frozen with the publication
    publication_id: Mapped[uuid.UUID]
    enrolment_id: Mapped[uuid.UUID]
    total_score: Mapped[Decimal] = mapped_column(Numeric(7, 2))
    average_score: Mapped[Decimal] = mapped_column(Numeric(5, 2))
    subjects_sat: Mapped[int] = mapped_column(SmallInteger)
    total_points: Mapped[int | None] = mapped_column(SmallInteger)
    division: Mapped[str | None] = mapped_column(String(3))
    class_position: Mapped[int] = mapped_column(SmallInteger)
    supersedes_id: Mapped[uuid.UUID | None]


class ReportCardComment(TenantMixin, Base):
    __tablename__ = "report_card_comments"
    publication_id: Mapped[uuid.UUID]
    enrolment_id: Mapped[uuid.UUID]
    class_teacher_comment: Mapped[str | None] = mapped_column(String(400))
    head_teacher_comment: Mapped[str | None] = mapped_column(String(400))


class ExamCandidate(TenantMixin, Base):
    """A student's candidate number for one exam session (admit cards)."""

    __tablename__ = "exam_candidates"
    exam_session_id: Mapped[uuid.UUID]
    enrolment_id: Mapped[uuid.UUID]
    candidate_no: Mapped[str] = mapped_column(String(20))
